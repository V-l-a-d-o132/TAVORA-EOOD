// Cache for Supabase-fetched lessons to avoid repeated requests
const supabaseCache: Record<string, LessonData | null> = {};

/**
 * Fetch lesson data from Supabase first, fallback to mock data.
 * Results are cached in memory for the session.
 */
export async function fetchLessonData(moduleId: string, lessonId?: string): Promise<LessonData | null> {
  const cacheKey = lessonId ? `${moduleId}-${lessonId}` : moduleId;
  
  // Return cached result if available
  if (cacheKey in supabaseCache) {
    return supabaseCache[cacheKey];
  }

  try {
    // Try with lessonId first
    let query = supabase
      .from('interactive_lessons')
      .select('*')
      .eq('module_id', moduleId);
    
    if (lessonId) {
      query = query.eq('lesson_id', lessonId);
    }

    let { data, error } = await query;

    // If no result with lessonId, try without (for module-level lessons like s01-m07)
    if ((!data || data.length === 0) && lessonId) {
      const { data: data2, error: error2 } = await supabase
        .from('interactive_lessons')
        .select('*')
        .eq('module_id', moduleId)
        .is('lesson_id', null);
      if (!error2 && data2 && data2.length > 0) {
        data = data2;
      }
    }

    if (!error && data && data.length > 0) {
      const record = data[0];
      const lessonData: LessonData = {
        id: record.id,
        title: record.title,
        subtitle: record.subtitle || '',
        duration: record.duration || '20 мин',
        slides: record.slides || [],
      };
      supabaseCache[cacheKey] = lessonData;
      return lessonData;
    }
  } catch {
    // Supabase not available or error — fall through to mock
  }

  // Fallback to mock data — try with lessonId first, then without
  let mockData = getLessonData(moduleId, lessonId);
  if (!mockData && lessonId) {
    mockData = getLessonData(moduleId);
  }
  supabaseCache[cacheKey] = mockData;
  return mockData;
}