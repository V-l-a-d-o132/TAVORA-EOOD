export function videoClientStage(moduleId: string) {
  const match = /^s02-m(0[1-9]|1[0-5])$/.exec(moduleId);
  if (!match) return null;
  const index = Number(match[1]) - 1;
  return { number: index + 1, title: VIDEO_CLIENT_ROUTE[index][0], result: VIDEO_CLIENT_ROUTE[index][1] };
}
export function videoClientEstimate(extraRevision: boolean, discount: boolean, quoteExtra = false) {
  const hours = VIDEO_CLIENT_PROJECT.work.reduce((sum, [, value]) => sum + value, 0) + (extraRevision ? 2 : 0);
  const labor = hours * VIDEO_CLIENT_PROJECT.rate;
  const price = VIDEO_CLIENT_PROJECT.price + (extraRevision && quoteExtra ? 40 : 0) - (discount ? 20 : 0);
  const cost = labor + VIDEO_CLIENT_PROJECT.expenses;
  return { hours, labor, price, cost, difference: price - cost };
}
